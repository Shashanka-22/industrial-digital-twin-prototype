import React from 'react';
import { useSimulation } from '../context/SimulationContext';
import { KPICard } from '../components/common/KPICard';
import { HealthGauge } from '../components/common/HealthGauge';
import { TelemetryCharts } from '../components/telemetry/TelemetryCharts';
import { FaultInjectionPanel } from '../components/telemetry/FaultInjectionPanel';
import {
  Gauge,
  Thermometer,
  Activity,
  Zap,
  RotateCw,
  AlertTriangle,
  Clock,
  ShieldCheck,
  CheckCircle2,
  AlertOctagon,
  Wrench,
  ArrowRight,
  Server,
} from 'lucide-react';
import { PageId } from '../components/common/Sidebar';

interface OverviewPageProps {
  onNavigate: (page: PageId) => void;
}

export const OverviewPage: React.FC<OverviewPageProps> = ({ onNavigate }) => {
  const {
    currentTelemetry,
    assetMetadata,
    settings,
    alarms,
    maintenanceActions,
    faultScenario,
    isConnected,
  } = useSimulation();

  // Status for KPI Cards
  const getVibStatus = () => {
    if (currentTelemetry.bearingVibrationRms >= settings.thresholds.vibrationCritical) return 'critical';
    if (currentTelemetry.bearingVibrationRms >= settings.thresholds.vibrationWarning) return 'warning';
    return 'nominal';
  };

  const getTempStatus = () => {
    if (currentTelemetry.statorTempC >= settings.thresholds.tempCritical) return 'critical';
    if (currentTelemetry.statorTempC >= settings.thresholds.tempWarning) return 'warning';
    return 'nominal';
  };

  const getCurrentStatus = () => {
    if (currentTelemetry.phaseCurrentA >= settings.thresholds.currentCritical) return 'critical';
    if (currentTelemetry.phaseCurrentA >= settings.thresholds.currentWarning) return 'warning';
    return 'nominal';
  };

  const getAnomalyStatus = () => {
    if (currentTelemetry.anomalyScore >= settings.thresholds.anomalyCritical) return 'critical';
    if (currentTelemetry.anomalyScore >= settings.thresholds.anomalyWarning) return 'warning';
    return 'nominal';
  };

  const recentAlarms = alarms.slice(0, 3);
  const primaryAction = maintenanceActions[0];

  return (
    <div className="space-y-6">
      {/* Stale Connection Warning Alert Banner if comms interrupted */}
      {(!isConnected || currentTelemetry.isStale) && (
        <div className="bg-rose-50 dark:bg-rose-950/60 border border-rose-200 dark:border-rose-900 rounded-xl p-4 flex items-center justify-between gap-4 text-rose-800 dark:text-rose-200 text-xs">
          <div className="flex items-center gap-2.5">
            <AlertOctagon className="w-5 h-5 text-rose-600 shrink-0" />
            <div>
              <span className="font-bold uppercase tracking-wider">
                Communications Interrupted · Telemetry Readings Stale
              </span>
              <p className="text-[11px] text-rose-700 dark:text-rose-300 mt-0.5">
                Physical sensor communication link lost. Readings are frozen at last valid sample timestamp. Simulation telemetry is marked stale.
              </p>
            </div>
          </div>
          <span className="font-mono text-xs px-2.5 py-1 bg-rose-200 dark:bg-rose-900 text-rose-900 dark:text-rose-100 rounded font-semibold shrink-0">
            STALE TELEMETRY
          </span>
        </div>
      )}

      {/* Asset Header Banner */}
      <div className="bg-white dark:bg-slate-900 rounded-xl border border-slate-200 dark:border-slate-800 p-5 shadow-xs flex flex-col lg:flex-row lg:items-center justify-between gap-4">
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <h2 className="text-lg sm:text-xl font-bold text-slate-900 dark:text-white tracking-tight">
              {assetMetadata.name}
            </h2>
            <span className="font-mono text-xs font-semibold px-2 py-0.5 rounded bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700">
              {assetMetadata.id}
            </span>
            <span
              className="text-xs font-mono font-medium text-teal-700 dark:text-teal-400 bg-teal-50 dark:bg-teal-950/60 px-2.5 py-0.5 rounded border border-teal-200 dark:border-teal-800"
              title="Motor telemetry and operating conditions are generated by the local simulation engine."
            >
              SIMULATION MODE — NO LIVE HARDWARE DATA
            </span>
            <span className="text-xs font-medium text-emerald-700 dark:text-emerald-400 bg-emerald-50 dark:bg-emerald-950/60 px-2 py-0.5 rounded border border-emerald-200 dark:border-emerald-800 flex items-center gap-1">
              <span className="w-1.5 h-1.5 rounded-full bg-emerald-500" />
              Continuous S1 Duty (76% Nominal)
            </span>
          </div>

          <p className="text-xs text-slate-500 dark:text-slate-400 mt-1">
            {assetMetadata.type} · Location: {assetMetadata.location} · Baseline: 1480 RPM, ~34.2 kW (~221 Nm). Motor telemetry and operating conditions are generated by the local simulation engine.
          </p>
        </div>

        {/* Technical Specification Chips */}
        <div className="flex flex-wrap items-center gap-3 text-xs font-mono text-slate-600 dark:text-slate-300">
          <div className="bg-slate-50 dark:bg-slate-800/80 px-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700">
            <span className="text-slate-400 block text-[10px] font-sans">Power (Rated vs Actual)</span>
            <span className="font-bold text-slate-900 dark:text-white">45.0 kW rated</span> ·{' '}
            <span className="text-teal-600 dark:text-teal-400 font-bold">{currentTelemetry.powerKw.toFixed(1)} kW operating</span>
          </div>
          <div className="bg-slate-50 dark:bg-slate-800/80 px-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700">
            <span className="text-slate-400 block text-[10px] font-sans">Current (Rated vs Actual)</span>
            <span className="font-bold text-slate-900 dark:text-white">81.5 A FLA</span> ·{' '}
            <span className="text-amber-600 dark:text-amber-400 font-bold">{currentTelemetry.phaseCurrentA.toFixed(1)} A</span>
          </div>
          <div className="bg-slate-50 dark:bg-slate-800/80 px-3 py-1.5 rounded-lg border border-slate-200 dark:border-slate-700">
            <span className="text-slate-400 block text-[10px] font-sans">Calculated Torque</span>
            <span className="font-bold text-teal-600 dark:text-teal-400">{currentTelemetry.torqueNm.toFixed(1)} Nm</span>
          </div>
        </div>
      </div>

      {/* Primary KPI Grid (6 Cards) */}
      <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-6 gap-3 sm:gap-4">
        <KPICard
          title="Shaft Speed"
          value={currentTelemetry.speedRpm.toFixed(0)}
          unit="RPM"
          subValue="Sync: 1500 RPM (2% slip)"
          icon={RotateCw}
          status={Math.abs(currentTelemetry.speedRpm - 1480) > 60 ? 'warning' : 'nominal'}
          thresholdNote="Nominal: 1475 - 1485 RPM"
        />

        <KPICard
          title="Operating Power"
          value={currentTelemetry.powerKw.toFixed(1)}
          unit="kW"
          subValue={`Torque: ${currentTelemetry.torqueNm.toFixed(1)} Nm`}
          icon={Gauge}
          status={currentTelemetry.powerKw > 46 ? 'warning' : 'nominal'}
          thresholdNote="Rated: 45.0 kW (S1 Duty)"
        />

        <KPICard
          title="Stator Winding Temp"
          value={currentTelemetry.statorTempC.toFixed(1)}
          unit="°C"
          subValue={`Simulated Raw ADC: %IW12 = ${currentTelemetry.rawTempAdc}`}
          icon={Thermometer}
          status={getTempStatus()}
          thresholdNote={`Trip Limit: ${settings.thresholds.tempCritical}°C`}
        />

        <KPICard
          title="Drive-End Vibration"
          value={currentTelemetry.bearingVibrationRms.toFixed(2)}
          unit="mm/s"
          subValue="Vibration Ref: ISO 10816-3 RMS"
          icon={Activity}
          status={getVibStatus()}
          thresholdNote={`Warn: ${settings.thresholds.vibrationWarning} · Crit: ${settings.thresholds.vibrationCritical}`}
        />

        <KPICard
          title="Phase Current (RMS)"
          value={currentTelemetry.phaseCurrentA.toFixed(1)}
          unit="A"
          subValue={`Rated FLA: 81.5 A (${((currentTelemetry.phaseCurrentA / 81.5) * 100).toFixed(0)}%)`}
          icon={Zap}
          status={getCurrentStatus()}
          thresholdNote={`Trip: ${settings.thresholds.currentCritical} A`}
        />

        <KPICard
          title="Anomaly Index"
          value={(currentTelemetry.anomalyScore * 100).toFixed(1)}
          unit="%"
          subValue={`Health: ${currentTelemetry.assetHealthPct}%`}
          icon={AlertTriangle}
          status={getAnomalyStatus()}
          thresholdNote="Threshold: 35% Warn · 65% Crit"
        />
      </div>

      {/* Middle Row: Health Gauge + Simulated Telemetry Chart */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Left Column: Health Gauge */}
        <div className="lg:col-span-1 flex flex-col gap-4">
          <HealthGauge
            healthPct={currentTelemetry.assetHealthPct}
            anomalyScore={currentTelemetry.anomalyScore}
            rulHours={currentTelemetry.estimatedRulHours}
            vibrationRms={currentTelemetry.bearingVibrationRms}
          />

          {/* Prescriptive Recommendation Card */}
          <div className="bg-white dark:bg-slate-900 rounded-xl border border-slate-200 dark:border-slate-800 p-4 shadow-xs">
            <div className="flex items-center justify-between pb-2 border-b border-slate-100 dark:border-slate-800">
              <div className="flex items-center gap-1.5">
                <Wrench className="w-4 h-4 text-teal-600" />
                <h4 className="font-semibold text-slate-900 dark:text-white text-xs">
                  Active Prescriptive Action
                </h4>
              </div>
              <span
                className={`text-[10px] font-bold px-1.5 py-0.5 rounded uppercase ${
                  primaryAction.priority === 'immediate'
                    ? 'bg-rose-100 text-rose-700 dark:bg-rose-950/80 dark:text-rose-300'
                    : primaryAction.priority === 'high'
                    ? 'bg-amber-100 text-amber-800 dark:bg-amber-950/80 dark:text-amber-300'
                    : 'bg-emerald-100 text-emerald-800 dark:bg-emerald-950/80 dark:text-emerald-300'
                }`}
              >
                {primaryAction.priority}
              </span>
            </div>

            <p className="text-xs font-semibold text-slate-800 dark:text-slate-200 mt-2">
              {primaryAction.title}
            </p>
            <p className="text-[11px] text-slate-600 dark:text-slate-400 mt-1 line-clamp-2">
              {primaryAction.recommendedAction}
            </p>

            <div className="flex items-center justify-between pt-2 mt-2 border-t border-slate-100 dark:border-slate-800 text-[11px] text-slate-500">
              <span>Target Window: {primaryAction.targetWindowHours}h</span>
              <button
                onClick={() => onNavigate('predictive_maint')}
                className="text-teal-700 dark:text-teal-400 font-medium hover:underline flex items-center gap-1"
              >
                Inspection Details <ArrowRight className="w-3 h-3" />
              </button>
            </div>
          </div>
        </div>

        {/* Right Column: Simulated Telemetry Line Chart */}
        <div className="lg:col-span-2">
          <TelemetryCharts />
        </div>
      </div>

      {/* Fault Injection Quick Bench */}
      <FaultInjectionPanel />

      {/* Bottom Row: Recent Alarms & End-to-End Pipeline Health */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {/* Recent Alarms */}
        <div className="bg-white dark:bg-slate-900 rounded-xl border border-slate-200 dark:border-slate-800 p-5 shadow-xs">
          <div className="flex items-center justify-between pb-3 border-b border-slate-100 dark:border-slate-800">
            <h4 className="font-semibold text-slate-900 dark:text-white text-sm">
              Recent Alarm Timeline (Alarm Management Concepts — ISA-18.2 Referenced)
            </h4>
            <button
              onClick={() => onNavigate('alarms')}
              className="text-xs text-teal-700 dark:text-teal-400 font-semibold hover:underline"
            >
              View All Alarms ({alarms.length}) →
            </button>
          </div>

          <div className="mt-3 space-y-2">
            {recentAlarms.length === 0 ? (
              <div className="text-center py-6 text-slate-400 text-xs">
                <CheckCircle2 className="w-6 h-6 mx-auto mb-1 text-emerald-500" />
                No active alarms recorded. Operating within nominal thresholds.
              </div>
            ) : (
              recentAlarms.map((alm) => (
                <div
                  key={alm.id}
                  className={`p-3 rounded-lg border text-xs flex flex-col gap-1 ${
                    alm.severity === 'critical'
                      ? 'bg-rose-50/60 dark:bg-rose-950/30 border-rose-200 dark:border-rose-900'
                      : 'bg-amber-50/60 dark:bg-amber-950/30 border-amber-200 dark:border-amber-900'
                  }`}
                >
                  <div className="flex items-center justify-between font-medium">
                    <span className="font-bold text-slate-900 dark:text-white">
                      {alm.sensor}
                    </span>
                    <span className="font-mono text-[10px] text-slate-500">{alm.timestamp}</span>
                  </div>
                  <p className="text-slate-600 dark:text-slate-300 text-[11px]">
                    {alm.description}
                  </p>
                  <div className="flex justify-between items-center text-[10px] font-mono text-slate-500 pt-1">
                    <span>
                      Val: {alm.measuredValue} {alm.unit} (Limit: {alm.threshold})
                    </span>
                    <span
                      className={`font-semibold uppercase ${
                        alm.acknowledged ? 'text-slate-400' : 'text-rose-600 dark:text-rose-400'
                      }`}
                    >
                      {alm.acknowledged ? 'ACKNOWLEDGED' : 'ACTIVE'}
                    </span>
                  </div>
                </div>
              ))
            )}
          </div>
        </div>

        {/* Real-Time Industrial Pipeline Link Status */}
        <div className="bg-white dark:bg-slate-900 rounded-xl border border-slate-200 dark:border-slate-800 p-5 shadow-xs space-y-3">
          <div className="flex items-center justify-between pb-3 border-b border-slate-100 dark:border-slate-800">
            <div>
              <h4 className="font-semibold text-slate-900 dark:text-white text-sm">
                Industrial Digital Twin Architecture Reference
              </h4>
              <p className="text-[11px] text-slate-500 dark:text-slate-400 mt-0.5">
                SIMULATION MODE — NO LIVE HARDWARE DATA · Local Simulation Engine Active
              </p>
            </div>
            <button
              onClick={() => onNavigate('architecture')}
              className="text-xs text-teal-700 dark:text-teal-400 font-semibold hover:underline"
            >
              Explore Architecture →
            </button>
          </div>

          <div className="space-y-2.5 text-xs">
            <div className="flex items-center justify-between p-2 rounded-lg bg-slate-50 dark:bg-slate-800/60 border border-slate-200 dark:border-slate-800">
              <div className="flex items-center gap-2">
                <span className="w-2 h-2 rounded-full bg-teal-500" />
                <span className="font-medium text-slate-900 dark:text-white">
                  Field I/O (ET 200SP ↔ S7-1500)
                </span>
              </div>
              <span className="font-mono text-[11px] text-teal-700 dark:text-teal-400 font-medium">
                Simulated I/O Model (PROFINET RT Reference)
              </span>
            </div>

            <div className="flex items-center justify-between p-2 rounded-lg bg-slate-50 dark:bg-slate-800/60 border border-slate-200 dark:border-slate-800">
              <div className="flex items-center gap-2">
                <span className={`w-2 h-2 rounded-full ${isConnected ? 'bg-amber-500' : 'bg-rose-500'}`} />
                <span className="font-medium text-slate-900 dark:text-white">
                  OT Gateway (PLC ↔ Edge IPC)
                </span>
              </div>
              <span className="font-mono text-[11px] text-slate-600 dark:text-slate-300">
                {isConnected ? 'OPC UA: Prepared / Disconnected (Local Engine Active)' : 'COMMUNICATION LOSS · READINGS STALE'}
              </span>
            </div>

            <div className="flex items-center justify-between p-2 rounded-lg bg-slate-50 dark:bg-slate-800/60 border border-slate-200 dark:border-slate-800">
              <div className="flex items-center gap-2">
                <span className="w-2 h-2 rounded-full bg-slate-400" />
                <span className="font-medium text-slate-900 dark:text-white">
                  Cloud Gateway (Edge IPC ↔ Insights Hub)
                </span>
              </div>
              <span className="font-mono text-[11px] text-slate-500">
                MQTT: Prepared / Disconnected
              </span>
            </div>

            <div className="flex items-center justify-between p-2 rounded-lg bg-slate-50 dark:bg-slate-800/60 border border-slate-200 dark:border-slate-800">
              <div className="flex items-center gap-2">
                <span className="w-2 h-2 rounded-full bg-emerald-500" />
                <span className="font-medium text-slate-900 dark:text-white">
                  Digital Twin Model Consistency Check
                </span>
              </div>
              <span className="font-mono text-[11px] text-emerald-600 dark:text-emerald-400 font-semibold">
                Simulated Model Convergence (Local Reference)
              </span>
            </div>
          </div>

          <div className="pt-2 border-t border-slate-100 dark:border-slate-800 text-[11px] text-slate-500 dark:text-slate-400">
            *Notice: OPC UA and MQTT endpoints are prepared architecture references (Disconnected in this deployment). All telemetry is generated by the local simulation engine.
          </div>
        </div>
      </div>
    </div>
  );
};
